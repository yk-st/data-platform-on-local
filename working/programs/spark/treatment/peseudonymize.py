# pseudonymize_from_wide.py
# Spark 3.5.5 (Scala 2.13) / Python 3.12 を想定
#
# 目的:
#   Iceberg ワイドテーブル `local_data_platform.slv_analytics.user_orders_wide`
#   を入力に、個人を識別しにくい “仮名加工” データを生成して
#   コンソールに表示するだけ（ファイル出力なし）。
#
#   - USER / ORDER を SHA-256 + SALT でハッシュ化
#   - 住所→都道府県・市区町村、年齢→5 歳帯
#   - 氏名・メールは AES-256 で暗号化し原文を削除
#   - 金額整合フラグを付与

from pyspark.sql import SparkSession
from pyspark.sql import functions as F

# ---------------------------------------------------------------------------
# 0. パラメータ
# ---------------------------------------------------------------------------
TABLE_NAME   = "local_data_platform.slv_entities.user_orders_wide"
SALT         = "X7q9@p$!"   # ※本番は KMS / SecretsManager などから注入
AES_KEY_HEX  = "00112233445566778899aabbccddeeff00112233445566778899aabbccddeeff"
HASH_LEN     = 16           # user_token / order_token の文字長

spark = (
    SparkSession.builder.appName("pseudonymize_from_wide")
    .config("spark.sql.shuffle.partitions", "200")
    .getOrCreate()
)

# ---------------------------------------------------------------------------
# 1. 入力テーブル読み込み
# ---------------------------------------------------------------------------
wide = spark.read.table(TABLE_NAME)

# ---------------------------------------------------------------------------
# 2. 仮名加工処理
# ---------------------------------------------------------------------------
key_bin = F.unhex(F.lit(AES_KEY_HEX))             # AES 鍵をバイナリ列に変換

pseudonymized = (
    wide
    # ── 2-1. トークン化 ─────────────────────────────────────────────
    .withColumn(
        "user_token",
        F.sha2(F.concat(F.lit(SALT), F.col("user_id").cast("string")), 256)
         .substr(1, HASH_LEN)
    )
    .withColumn(
        "order_token",
        F.sha2(F.concat(F.lit(SALT), F.col("order_id").cast("string")), 256)
         .substr(1, HASH_LEN)
    )

    # ── 2-2. 準識別子の汎化 ───────────────────────────────────────
    # 住所 → 都道府県／市区町村
    .withColumn(
        "prefecture",
        F.expr(r"regexp_extract(trim(`address`), '^(.+?[都道府県])', 1)")
    )
    .withColumn(
        "city",
        F.expr(r"regexp_extract(trim(`address`), '^.+?[都道府県]\s*(.+?市|.+?区)', 1)")
    )

    # 年齢帯 (5 歳刻み)
    .withColumn(
        "age_band",
        F.concat(
            (F.floor(F.months_between(F.current_date(), F.col("birth_date")) / 12 / 5) * 5).cast("int"),
            F.lit("-"),
            ((F.floor(F.months_between(F.current_date(), F.col("birth_date")) / 12 / 5) * 5) + 4).cast("int")
        )
    )

    # ── 2-3. 直接識別子の暗号化 ──────────────────────────────────
    .withColumn("name_enc",  F.aes_encrypt(F.col("user_name"),  key_bin))
    .withColumn("email_enc", F.aes_encrypt(F.col("email"), key_bin))
    .drop("user_name", "email", "password", "address", "birth_date")

    # ── 2-4. 品質フラグ(ゼロコントロール。任意) ─────────────────────────────────────────
    .withColumn(
        "total_mismatch_flg",
        (F.col("subtotal_usd") + F.col("tax_usd") != F.col("total_usd")).cast("boolean")
    )
)

# ---------------------------------------------------------------------------
# 3. コンソール出力のみ
# ---------------------------------------------------------------------------
pseudonymized.select(
        "order_id", "order_token",
        "user_id", "user_token",
        "prefecture", "city", "age_band",
        "category", "subtotal_usd", "tax_usd", "total_usd",
        "total_mismatch_flg"
    ).filter(F.col("order_id").isin([34,14])).show(100, truncate=False)

print("✅  Pseudonymization finished (console output only)")

